// Owner mobile PWA service worker (Phase 9.2). Two jobs: a minimal
// app-shell cache so the owner-relevant screens (dashboard, alerts,
// analytics, indents) open instantly on a flaky connection, and push
// notification display/routing. Deliberately not a full offline-first
// cache of the whole app — the POS billing screen already has its own,
// much more careful offline-write handling (src/lib/offline) that this
// must not interfere with, so navigation requests always try the network
// first and only fall back to the cache when it's genuinely unreachable.

const CACHE_NAME = "owner-pwa-shell-v1";
const SHELL_URLS = ["/dashboard", "/alerts", "/analytics", "/indents"];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(SHELL_URLS).catch(() => {}))
  );
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;
  if (!SHELL_URLS.includes(url.pathname)) return;

  event.respondWith(
    fetch(event.request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});

self.addEventListener("push", (event) => {
  if (!event.data) return;
  let payload;
  try {
    payload = event.data.json();
  } catch {
    payload = { title: "Pharmacy Billing", body: event.data.text(), url: "/dashboard" };
  }
  event.waitUntil(
    self.registration.showNotification(payload.title || "Pharmacy Billing", {
      body: payload.body,
      icon: "/icons/icon-192.png",
      badge: "/icons/icon-192.png",
      data: { url: payload.url || "/dashboard" },
    })
  );
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = event.notification.data?.url || "/dashboard";
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((clients) => {
      for (const client of clients) {
        if (client.url.includes(url) && "focus" in client) return client.focus();
      }
      if (self.clients.openWindow) return self.clients.openWindow(url);
    })
  );
});
